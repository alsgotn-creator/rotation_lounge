export function doubleTopic(kind: TopicKind, round: number, step: number, total: number) {
  const l = DOUBLE_TOPICS[kind], size = Math.max(1, Math.floor(l.length / Math.max(1, total)));
  return l[((round - 1) * size + (((step % size) + size) % size)) % l.length];
}

export const cardById = (id: string) => CARDS.find((c) => c.id === id) ?? null;

/**
 * total번 중 n번째 라운드의 카드 묶음: 종류별 카드를 라운드 수만큼 나눠 n번째 묶음만 쓴다.
 * 라운드마다 다른 묶음이라 어느 테이블로 옮겨 가도 이미 본 카드는 다시 안 나온다.
 */
export function roundCards(kind: CardKind, round: number, total: number) {
  const l = CARDS.filter((c) => c.kind === kind), size = Math.max(1, Math.floor(l.length / Math.max(1, total)));
  return Array.from({ length: size }, (_, i) => l[((round - 1) * size + i) % l.length]);
}

/**
 * 이번 라운드 묶음에서 다음 카드. 같은 종류를 보고 있었으면 그다음 장이라 묶음을 한 바퀴 돌기 전엔 안 겹친다.
 * shortcut: 다른 종류로 갔다 돌아오면 묶음 안 아무 장에서 다시 시작해 같은 라운드 안에서 겹칠 수 있다. 본 카드 기록이 필요해지면 game_plays 에 칸 추가.
 */
export function drawCard(kind: CardKind, round: number, total: number, currentId?: string | null, rnd = Math.random): GameCard {
  const pool = roundCards(kind, round, total), i = pool.findIndex((c) => c.id === currentId);
  return pool[i >= 0 ? (i + 1) % pool.length : Math.floor(rnd() * pool.length)];
}
